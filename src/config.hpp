    auto pos2m(const std::vector<int> &padPos, const int caseSize) {
        std::vector<std::vector<int>> shuffleM;
        for (int i = 0; i < padPos.size(); ++i) {
            std::vector<int> tmp;
            for (int j = 0; j < caseSize; ++j) tmp.push_back(0);

            if (padPos.at(i) != -1) tmp.at(padPos.at(i)) = 1;

            shuffleM.push_back(tmp);
        }
        return shuffleM;
    }
